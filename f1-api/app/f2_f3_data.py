def get_series_meetings(series: str, year: int = 2026) -> List[Dict[str, Any]]:
    """Retorna a lista de reuniões (meetings) da categoria para o ano solicitado."""
    if year != 2026:
        return []
    if series == "f2":
        return list(F2_2026_MEETINGS)
    if series == "f3":
        return list(F3_2026_MEETINGS)
    return []


def get_series_sessions(series: str, year: int = 2026) -> List[Dict[str, Any]]:
    """Retorna todas as sessões planas da série para o ano solicitado."""
    meetings = get_series_meetings(series, year)
    flat_sessions: List[Dict[str, Any]] = []
    for m in meetings:
        for s in m.get("sessions", []):
            item = dict(s)
            item.setdefault("meeting_key", m["meeting_key"])
            item.setdefault("meeting_name", m["meeting_name"])
            item.setdefault("circuit_short_name", m.get("circuit_short_name"))
            item.setdefault("country_name", m.get("country_name"))
            item.setdefault("location", m.get("location"))
            item.setdefault("year", m.get("year", 2026))
            flat_sessions.append(item)
    return flat_sessions


def get_series_session_by_key(series: str, session_key: int) -> Optional[Dict[str, Any]]:
    """Busca uma sessão pelo session_key na série especificada."""
    for s in get_series_sessions(series, 2026):
        if s.get("session_key") == session_key:
            return s
    return None
